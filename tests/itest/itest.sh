# copy in SOURCE, close SOURCE, then focus TARGET. A helper holds focus (and keeps a keyboard
# on the seat, which the selection needs to reach anyone) while SOURCE goes away; only the
# focused client may paste, so TARGET is focused last, as a user would before pasting.
copy_close_focus() { # SOURCE TARGET
    local sx sy tx ty
    read -r sx sy < <(center "$1")
    echo "select $sx $sy $MW $MH" >&7
    wait_line "$OUT/$1.log" SELECTION_SET 5 || bad "$1 set the selection"
    sleep 0.5                    # glowbuffer reads the clipboard now
    start_helper "h-$1"
    echo quit >&7                # close the app that copied
    exec 7>&-
    wait_line "$OUT/$1.log" BYE 5 || bad "$1 exited"
    sleep 0.3
    read -r tx ty < <(center "$2") || true
    echo "focus $tx $ty $MW $MH" >&8
}

echo "itest: paste after the copying app closed"
start_target t10 host --selection-delay 1500 --accept "text/plain;charset=utf-8" --out "$OUT/t10.data"
start_source s10 --offer "text/plain;charset=utf-8=$TEXT" --offer "image/png=$IMAGE"
copy_close_focus s10 t10
wait_line "$OUT/t10.log" DONE 10 || bad "target read the kept clipboard"
check "clipboard kept after its app closed" cmp -s "$TEXT" "$OUT/t10.data"
stop_clients

