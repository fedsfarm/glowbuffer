#!/bin/bash
# itest.sh — glowbuffer end to end, against the real Hyprland binary, where nobody can see it.
#
#   tests/itest/itest.sh [path/to/glowbuffer.so]      (default: build/glowbuffer.so)
#
# A compositor plugin runs inside the compositor, so testing it in the user's session would
# risk the session. This never touches it:
#   * the whole run is re-executed under `env -i` with a fresh XDG_RUNTIME_DIR and its own
#     `dbus-run-session`: no WAYLAND_DISPLAY, DISPLAY, HYPRLAND_INSTANCE_SIGNATURE or session
#     bus of the real desktop is even visible, and the document portal the bridge talks to
#     is a private instance with its own FUSE mount;
#   * the outer compositor is weston on its headless backend (no window anywhere), and the
#     Hyprland under test runs nested inside it with HYPRLAND_NO_SD_VARS set, so it does not
#     push its environment into systemd or D-Bus activation either. Not cage, the usual
#     headless host: Hyprland's Wayland backend needs xdg_wm_base v6 and cage 0.3 offers v5;
#   * input comes from the test client's own virtual pointer and keyboard, which exist only
#     in that nested Hyprland.
#
# A sandboxed app is faked the way the plugin detects one: the target client runs under
# bwrap with a /.flatpak-info naming org.glowbuffer.Test.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
SO=$(realpath "${1:-$ROOT/build/glowbuffer.so}")
OUT="$HERE/out"

# ── outer: isolate, then re-run inside the isolation ──────────────────────────────────────
if [ -z "${GLOWBUFFER_ITEST_INNER:-}" ]; then
    for cmd in weston Hyprland hyprctl bwrap dbus-run-session wayland-scanner cc python3 fusermount3; do
        command -v "$cmd" >/dev/null || { echo "itest: missing $cmd" >&2; exit 2; }
    done
    [ -f "$SO" ] || { echo "itest: no plugin at $SO (scripts/build-remote.sh builds it)" >&2; exit 2; }

    rm -rf "$OUT"
    mkdir -p "$OUT/gen" "$OUT/files"
    for xml in "$HERE"/protocols/*.xml; do
        base=$(basename "$xml" .xml)
        wayland-scanner client-header "$xml" "$OUT/gen/$base-client-protocol.h"
        wayland-scanner private-code "$xml" "$OUT/gen/$base-protocol.c"
    done
    # shellcheck disable=SC2046
    cc -std=gnu11 -O1 -Wall -Wextra -Werror -Wno-unused-parameter -I"$OUT/gen" "$HERE/client.c" "$OUT"/gen/*.c \
        $(pkg-config --cflags --libs wayland-client xkbcommon libsystemd) -o "$OUT/gbclient"

    # Short on purpose: Hyprland's IPC sockets live at $RT/hypr/<60-char signature>/.socket2.sock
    # and a unix socket path stops at 108 bytes ("Socket2 path is too long", no hyprctl).
    RT=$(mktemp -d /tmp/gb.XXXXXX)
    chmod 700 "$RT"
    status=0
    env -i HOME="$HOME" USER="${USER:-$(id -un)}" PATH="$PATH" LANG=C.UTF-8 \
        XDG_RUNTIME_DIR="$RT" GLOWBUFFER_ITEST_INNER=1 GLOWBUFFER_ITEST_STOP="${GLOWBUFFER_ITEST_STOP:-}" GLOWBUFFER_ITEST_WLDEBUG="${GLOWBUFFER_ITEST_WLDEBUG:-}" \
        dbus-run-session -- "$0" "$SO" || status=$?
    # the private document portal exits with its bus; make sure its mount went with it
    fusermount3 -uz "$RT/doc" 2>/dev/null || true
    rm -rf "$RT" 2>/dev/null || echo "itest: could not remove $RT" >&2
    exit "$status"
fi

# ── inner: everything below sees only the private runtime dir and bus ─────────────────────
RT="$XDG_RUNTIME_DIR"
fail=0
pass() { printf '  ok    %s\n' "$*"; }
bad() { printf '  FAIL  %s\n' "$*"; fail=1; }
check() { # check DESCRIPTION COMMAND...
    local what=$1
    shift
    if "$@"; then pass "$what"; else bad "$what"; fi
}
has() { grep -qxF -- "$2" "$1"; }   # has LOG LINE
lacks() { ! grep -qxF -- "$2" "$1"; }

cleanup() {
    [ -n "${HLOG:-}" ] && cp "$HLOG" "$OUT/hyprland.log" 2>/dev/null
    local pids
    pids=$(jobs -p)
    [ -n "$pids" ] || return 0
    kill $pids 2>/dev/null || true
    sleep 1
    kill -KILL $pids 2>/dev/null || true
    wait 2>/dev/null || true
}
trap cleanup EXIT

cat >"$OUT/hypr.lua" <<'EOF'
-- generated by tests/itest/itest.sh
hl.config({
  misc = { disable_hyprland_logo = true, disable_splash_rendering = true, force_default_wallpaper = 0 },
  debug = { disable_logs = false },
  input = { follow_mouse = 1 },
  animations = { enabled = false },
})
EOF

env ${GLOWBUFFER_ITEST_WLDEBUG:+WAYLAND_DEBUG=server} weston --backend=headless --renderer=gl --shell=kiosk --width=1600 --height=900 --idle-time=0 \
    --socket=wl-host >"$OUT/weston.log" 2>&1 &
for _ in $(seq 1 100); do [ -S "$RT/wl-host" ] && break; sleep 0.1; done
[ -S "$RT/wl-host" ] || { echo "itest: weston did not come up" >&2; tail -20 "$OUT/weston.log" >&2; exit 1; }

# wlproxy.py raises the protocol versions weston advertises to the ones Hyprland insists on;
# see its docstring for why that is safe for exactly those three globals.
env ${GLOWBUFFER_ITEST_WLDEBUG:+WLPROXY_DEBUG=1} python3 -I "$HERE/wlproxy.py" "$RT/wl-relay" "$RT/wl-host" >"$OUT/wlproxy.log" 2>&1 &
for _ in $(seq 1 50); do [ -S "$RT/wl-relay" ] && break; sleep 0.1; done

# LIBSEAT_BACKEND=seatd: there is no seatd socket, so the DRM backend Hyprland always tries
# first fails at once instead of asking logind to take control of the real session.
env WAYLAND_DISPLAY=wl-relay LIBSEAT_BACKEND=seatd HYPRLAND_NO_SD_VARS=1 HYPRLAND_NO_SD_NOTIFY=1 ${GLOWBUFFER_ITEST_WLDEBUG:+WAYLAND_DEBUG=client} \
    Hyprland --config "$OUT/hypr.lua" >"$OUT/hyprland.stdout" 2>&1 &

SIG="" WL=""
for _ in $(seq 1 200); do
    for lock in "$RT"/hypr/*/hyprland.lock; do
        [ -r "$lock" ] || continue
        SIG=$(basename "$(dirname "$lock")")
        WL=$(sed -n 2p "$lock")
    done
    [ -n "$SIG" ] && [ -n "$WL" ] && HYPRLAND_INSTANCE_SIGNATURE=$SIG hyprctl version >/dev/null 2>&1 && break
    sleep 0.1
done
[ -n "$SIG" ] || { echo "itest: nested Hyprland did not come up; see $OUT/hyprland.stdout" >&2; tail -20 "$OUT/hyprland.stdout" >&2; exit 1; }
export HYPRLAND_INSTANCE_SIGNATURE=$SIG WAYLAND_DISPLAY=$WL
HLOG="$RT/hypr/$SIG/hyprland.log"
echo "itest: nested Hyprland $SIG on $WL ($(hyprctl version | head -1))"

# MW x MH: the layout in LOGICAL pixels, which is what window positions are in and what the
# virtual pointer's absolute extents must match (Hyprland may pick a scale for the output).
MW="" MH=""
for _ in $(seq 1 100); do
    read -r MW MH < <(hyprctl monitors -j | python3 -I -c 'import json,sys; m=json.load(sys.stdin); m=[x for x in m if x["width"] > 0]; print(round(m[0]["width"] / m[0]["scale"]), round(m[0]["height"] / m[0]["scale"])) if m else print()') || true
    [ -n "$MW" ] && break
    sleep 0.1
done
[ -n "$MW" ] || { echo "itest: the nested Hyprland never got an output" >&2; exit 1; }
if [ "${GLOWBUFFER_ITEST_STOP:-}" = config ]; then
    # the lua spelling README documents: a key set in hyprland.lua reaches the plugin
    printf '\nhl.config({ plugin = { glowbuffer = { modifiers = false } } })\n' >>"$OUT/hypr.lua"
    hyprctl plugin load "$SO" >/dev/null 2>&1
    sleep 0.5
    hyprctl -j glowbuffer
    exit 0
fi
if [ "${GLOWBUFFER_ITEST_STOP:-}" = boot ]; then
    pkill -USR1 -f "wlproxy.py $RT/wl-relay" 2>/dev/null; sleep 0.5
    hyprctl monitors -j; hyprctl monitors; cp "$HLOG" "$OUT/hyprland.log"; exit 0
fi

# center CLASS -> "X Y" of that window, in layout coordinates
center() {
    hyprctl clients -j | python3 -I -c '
import json, sys
for c in json.load(sys.stdin):
    if c["class"] == sys.argv[1]:
        print(c["at"][0] + c["size"][0] // 2, c["at"][1] + c["size"][1] // 2)
        break' "$1"
}

wait_line() { # wait_line LOG LINE [SECONDS]
    local i
    for i in $(seq 1 $(( ${3:-10} * 10 ))); do
        grep -qxF -- "$2" "$1" 2>/dev/null && return 0
        sleep 0.1
    done
    return 1
}

CLIENTS=()
FLATPAK_INFO="$OUT/flatpak-info"
printf '[Application]\nname=org.glowbuffer.Test\nruntime=runtime/org.glowbuffer.Platform/x86_64/1\n' >"$FLATPAK_INFO"

# start_target NAME sandboxed|host ARGS...
start_target() {
    local name=$1 mode=$2
    shift 2
    if [ "$mode" = sandboxed ]; then
        bwrap --unshare-pid --die-with-parent \
            --ro-bind /usr /usr --symlink usr/lib64 /lib64 --symlink usr/lib /lib --symlink usr/bin /bin \
            --ro-bind /etc /etc --proc /proc --dev /dev \
            --bind "$RT" "$RT" --bind "$OUT" "$OUT" \
            --ro-bind "$FLATPAK_INFO" /.flatpak-info \
            -- "$OUT/gbclient" target "$name" "$@" >"$OUT/$name.log" 2>&1 &
    else
        "$OUT/gbclient" target "$name" "$@" >"$OUT/$name.log" 2>&1 &
    fi
    CLIENTS+=($!)
    wait_line "$OUT/$name.log" READY || { echo "itest: $name never mapped" >&2; cat "$OUT/$name.log" >&2; exit 1; }
}

# the bwrap jail a fake Flatpak app runs in
sandboxed() {
    bwrap --unshare-pid --die-with-parent \
        --ro-bind /usr /usr --symlink usr/lib64 /lib64 --symlink usr/lib /lib --symlink usr/bin /bin \
        --ro-bind /etc /etc --proc /proc --dev /dev \
        --bind "$RT" "$RT" --bind "$OUT" "$OUT" \
        --ro-bind "$FLATPAK_INFO" /.flatpak-info \
        -- "$@"
}

# start_source NAME ARGS...   (commands go to fd 7; SANDBOXED_SOURCE=1 jails it)
start_source() {
    local name=$1
    shift
    rm -f "$OUT/$name.in"
    mkfifo "$OUT/$name.in"
    if [ "${SANDBOXED_SOURCE:-}" = 1 ]; then
        sandboxed "$OUT/gbclient" source "$name" "$@" <"$OUT/$name.in" >"$OUT/$name.log" 2>&1 &
    else
        "$OUT/gbclient" source "$name" "$@" <"$OUT/$name.in" >"$OUT/$name.log" 2>&1 &
    fi
    CLIENTS+=($!)
    exec 7>"$OUT/$name.in"
    wait_line "$OUT/$name.log" READY || { echo "itest: $name never mapped" >&2; cat "$OUT/$name.log" >&2; exit 1; }
    settle
}

# Wait until two windows are mapped and their geometry stops changing: positions read while
# the layout is still splitting point the pointer at the wrong window.
settle() {
    local prev="" cur i
    for i in $(seq 1 50); do
        cur=$(hyprctl clients -j | python3 -I -c 'import json,sys; c=json.load(sys.stdin); print(sorted((x["class"], tuple(x["at"]), tuple(x["size"])) for x in c) if len(c) >= 2 else "")')
        [ -n "$cur" ] && [ "$cur" = "$prev" ] && return 0
        prev=$cur
        sleep 0.1
    done
    echo "itest: layout never settled: $cur" >&2
}

# start_helper NAME: a second source on fd 8, for input while fd 7's source is busy
start_helper() {
    local name=$1
    rm -f "$OUT/$name.in"
    mkfifo "$OUT/$name.in"
    "$OUT/gbclient" source "$name" <"$OUT/$name.in" >"$OUT/$name.log" 2>&1 &
    CLIENTS+=($!)
    exec 8>"$OUT/$name.in"
    wait_line "$OUT/$name.log" READY || { echo "itest: $name never mapped" >&2; exit 1; }
}

stop_clients() {
    echo quit >&7 2>/dev/null || true
    echo quit >&8 2>/dev/null || true
    exec 7>&- 8>&-
    sleep 0.3
    [ ${#CLIENTS[@]} -gt 0 ] && kill "${CLIENTS[@]}" 2>/dev/null || true
    CLIENTS=()
    sleep 0.3
}

# drag SOURCE TARGET [shift]
drag() {
    local s t
    s=$(center "$1")
    t=$(center "$2")
    [ -n "$s" ] && [ -n "$t" ] || { bad "window positions for $1/$2"; return; }
    echo "drag $s $t $MW $MH 600 ${3:-}" >&7
    wait_line "$OUT/$1.log" DONE 15 || bad "$1 finished its drag"
    wait_line "$OUT/$2.log" DONE 5 || true
}

# ── fixtures ──────────────────────────────────────────────────────────────────────────────
LINKS="$OUT/links.txt"
printf 'https://example.com/a\r\nhttps://example.com/b\r\n' >"$LINKS"
printf 'glowbuffer test\n' >"$OUT/files/a b.txt"
FILE_URI="file://$(python3 -I -c 'import sys, urllib.parse; print(urllib.parse.quote(sys.argv[1]))' "$OUT/files/a b.txt")"
FILES="$OUT/files.txt"
printf '%s\r\nhttps://example.com/keep\r\n' "$FILE_URI" >"$FILES"
COPIED="$OUT/copied.txt"
printf 'copy\n%s' "$FILE_URI" >"$COPIED"

URI=text/uri-list

# ── 0. control: the bug, without the plugin ───────────────────────────────────────────────
echo "itest: control run, plugin NOT loaded"
start_target t0 host --actions 1 --preferred 1 --accept $URI --out "$OUT/t0.data"
start_source s0 --actions 7 --offer "$URI=$LINKS"
drag s0 t0
check "control: stock Hyprland announces MOVE to a copy-only target (the bug)" has "$OUT/t0.log" "ACTION 2"
hyprctl cursorpos >"$OUT/cursorpos.txt" 2>&1 || true
hyprctl clients -j >"$OUT/clients0.json" 2>&1 || true
stop_clients
[ "${GLOWBUFFER_ITEST_STOP:-}" = control ] && { cp "$HLOG" "$OUT/hyprland.log"; exit "$fail"; }

# ── load ──────────────────────────────────────────────────────────────────────────────────
echo "itest: loading $SO"
hyprctl plugin load "$SO" >"$OUT/load.txt" 2>&1 || true
check "plugin loads" grep -qxF ok "$OUT/load.txt"
hyprctl glowbuffer >"$OUT/status0.txt" 2>&1 || true
check "hook active" grep -q '^hook: *active' "$OUT/status0.txt"

# ── 1. copy-only target ───────────────────────────────────────────────────────────────────
echo "itest: copy-only target"
start_target t1 host --actions 1 --preferred 1 --accept $URI --out "$OUT/t1.data"
start_source s1 --actions 7 --offer "$URI=$LINKS"
drag s1 t1
check "no MOVE announced" lacks "$OUT/t1.log" "ACTION 2"
check "COPY negotiated" has "$OUT/t1.log" "ACTION 1"
check "dropped as copy" has "$OUT/t1.log" "DROP action=1"
check "data delivered intact" cmp -s "$LINKS" "$OUT/t1.data"
check "source told COPY" has "$OUT/s1.log" "SRC_ACTION 1"
check "source finished" has "$OUT/s1.log" "SRC_FINISHED"
check "nothing announced before enter" python3 -I -c '
import sys
lines = open(sys.argv[1]).read().split("\n")
sys.exit(0 if lines.index("ENTER") < next(i for i, l in enumerate(lines) if l.startswith("ACTION ")) else 1)' "$OUT/t1.log"
stop_clients

# ── 2. target prefers move ────────────────────────────────────────────────────────────────
echo "itest: target prefers move"
start_target t2 host --actions 3 --preferred 2 --accept $URI --out "$OUT/t2.data"
start_source s2 --actions 7 --offer "$URI=$LINKS"
drag s2 t2
check "MOVE negotiated" has "$OUT/t2.log" "ACTION 2"
check "dropped as move" has "$OUT/t2.log" "DROP action=2"
check "source told MOVE" has "$OUT/s2.log" "SRC_ACTION 2"
stop_clients

# ── 3. Shift forces move ──────────────────────────────────────────────────────────────────
echo "itest: Shift held during the drag"
start_target t3 host --actions 3 --preferred 1 --accept $URI --out "$OUT/t3.data"
start_source s3 --actions 7 --offer "$URI=$LINKS"
drag s3 t3 shift
check "COPY first (target preference)" has "$OUT/t3.log" "ACTION 1"
check "Shift switches to MOVE" has "$OUT/t3.log" "ACTION 2"
check "dropped as move" has "$OUT/t3.log" "DROP action=2"
stop_clients

# ── 4. file bridge, drag into a sandboxed app ─────────────────────────────────────────────
# the portal path a rewritten line must name: file://<runtime>/doc/<id>/a%20b.txt
check_bridged() { # check_bridged DATAFILE
    python3 -I - "$1" "$RT" "$OUT/files/a b.txt" <<'EOF'
import os, re, sys, urllib.parse
data, rt, original = open(sys.argv[1], "rb").read().decode(), sys.argv[2], sys.argv[3]
m = re.search(r"file://(" + re.escape(rt) + r"/doc/([^/]+)/a%20b\.txt)", data)
if not m:
    print("    no portal path in:", repr(data)); sys.exit(1)
path, doc = urllib.parse.unquote(m.group(1)), m.group(2)
want = open(original, "rb").read()
if open(path, "rb").read() != want:
    print("    portal file differs"); sys.exit(1)
granted = os.path.join(rt, "doc", "by-app", "org.glowbuffer.Test", doc, "a b.txt")
if open(granted, "rb").read() != want:
    print("    not granted to org.glowbuffer.Test"); sys.exit(1)
EOF
}

echo "itest: drag files into a sandboxed app"
# the source is a file manager by class: the bridge takes file lists from those only
start_target t4 sandboxed --actions 1 --preferred 1 --accept $URI --out "$OUT/t4.data"
start_source nemo --actions 7 --offer "$URI=$FILES"
drag nemo t4
check "dropped" has "$OUT/t4.log" "DROP action=1"
check "file rewritten to a portal path the app was granted" check_bridged "$OUT/t4.data"
check "link line untouched, CRLF kept" grep -q $'^https://example.com/keep\r$' "$OUT/t4.data"
stop_clients

# ── 4b. the same drag from an app that is not a file manager: not shared ──────────────────
# a browser's drag carries whatever URIs the page put in it, file:// included
echo "itest: drag file URIs from a non-file-manager into a sandboxed app"
start_target t4b sandboxed --actions 1 --preferred 1 --accept $URI --out "$OUT/t4b.data"
start_source brave-origin --actions 7 --offer "$URI=$FILES"
drag brave-origin t4b
check "list from a browser forwarded unchanged, nothing exported" cmp -s "$FILES" "$OUT/t4b.data"
stop_clients

# ── 4c. a sandboxed app posing as a file manager: not shared ──────────────────────────────
# its paths resolve in its own mount namespace; opening them from the compositor would let
# its symlinks and ".." reach any host file
echo "itest: drag file URIs from a sandboxed app posing as a file manager"
start_target t4c sandboxed --actions 1 --preferred 1 --accept $URI --out "$OUT/t4c.data"
SANDBOXED_SOURCE=1 start_source nemo --actions 7 --offer "$URI=$FILES"
drag nemo t4c
check "list from a sandboxed source forwarded unchanged" cmp -s "$FILES" "$OUT/t4c.data"
stop_clients

# ── 5. same drag into a host app: bytes unchanged ─────────────────────────────────────────
echo "itest: drag files into a host app"
start_target t5 host --actions 1 --preferred 1 --accept $URI --out "$OUT/t5.data"
start_source pcmanfm --actions 7 --offer "$URI=$FILES"
drag pcmanfm t5
check "host app gets the list byte for byte" cmp -s "$FILES" "$OUT/t5.data"
stop_clients

# ── 6. file bridge, paste into a sandboxed app ────────────────────────────────────────────
echo "itest: paste copied files into a sandboxed app"
start_target t6 sandboxed --selection --accept x-special/gnome-copied-files --out "$OUT/t6.data"
start_source caja --offer "x-special/gnome-copied-files=$COPIED" --offer "$URI=$FILES"
read -r sx sy < <(center caja)
read -r tx ty < <(center t6)
echo "select $sx $sy $MW $MH" >&7
wait_line "$OUT/caja.log" SELECTION_SET 5 || bad "selection set"
echo "focus $tx $ty $MW $MH" >&7
wait_line "$OUT/t6.log" DONE 10 || bad "paste target read the selection"
check "pasted file rewritten to a granted portal path" check_bridged "$OUT/t6.data"
check "copy header kept" grep -q '^copy$' "$OUT/t6.data"
stop_clients

# ── 7. an image pasted into a file manager becomes a file ─────────────────────────────────
# the class is what decides: a test client named "thunar" stands in for Thunar
IMAGE="$OUT/image.png"
printf '\x89PNG\r\n\x1a\nnot really a png, compared byte for byte\n' >"$IMAGE"

paste_to() { # paste_to SOURCE TARGET: select in SOURCE, then focus TARGET
    local sx sy tx ty
    read -r sx sy < <(center "$1")
    read -r tx ty < <(center "$2")
    echo "select $sx $sy $MW $MH" >&7
    wait_line "$OUT/$1.log" SELECTION_SET 5 || bad "$1 set the selection"
    echo "focus $tx $ty $MW $MH" >&7
}

echo "itest: paste an image into a file manager"
start_target thunar host --selection --accept x-special/gnome-copied-files --out "$OUT/thunar.data"
start_source s7 --offer "image/png=$IMAGE"
paste_to s7 thunar
wait_line "$OUT/thunar.log" DONE 10 || bad "file manager read the pasted file list"
check "file manager offered a file list" grep -q '^SELECTION image/png,x-special/gnome-copied-files,text/uri-list$' "$OUT/thunar.log"
check "image saved as a file with the clipboard's bytes" python3 -I - "$OUT/thunar.data" "$RT" "$IMAGE" <<'PY'
import re, sys, urllib.parse
data, rt, image = open(sys.argv[1]).read(), sys.argv[2], sys.argv[3]
m = re.fullmatch(r"copy\nfile://(" + re.escape(rt) + r"/glowbuffer/Pasted%20image%20[0-9-]+%20[0-9-]+\.png)", data)
if not m:
    print("    unexpected list:", repr(data)); sys.exit(1)
sys.exit(0 if open(urllib.parse.unquote(m.group(1)), "rb").read() == open(image, "rb").read() else 1)
PY
stop_clients

# ── 7b. the same, from wl-copy (grim - | wl-copy): a data-control source ───────────────────
if command -v wl-copy >/dev/null; then
    echo "itest: paste a wl-copy image into a file manager"
    rm -f "$OUT/thunar.log"
    start_target thunar host --selection --accept x-special/gnome-copied-files --out "$OUT/thunar2.data"
    # a helper client only for its virtual keyboard: without a keyboard on the seat no window
    # has keyboard focus, and the selection goes only to the focused one
    start_source s7b
    read -r tx ty < <(center thunar)
    echo "focus $tx $ty $MW $MH" >&7
    wait_line "$OUT/s7b.log" FOCUSED 5 || true
    wl-copy --foreground --type image/png <"$IMAGE" &
    CLIENTS+=($!)
    wait_line "$OUT/thunar.log" DONE 10 || bad "file manager read the wl-copy image as a file"
    check "wl-copy image saved as a file" bash -c 'f=$(sed -n "2s|^file://||p" "$1" | python3 -I -c "import sys,urllib.parse; print(urllib.parse.unquote(sys.stdin.read().strip()))"); cmp -s "$f" "$2"' _ "$OUT/thunar2.data" "$IMAGE"
    stop_clients
fi

# ── 8. the same image in any other app stays an image ─────────────────────────────────────
echo "itest: paste an image into a non-file-manager"
start_target t8 host --selection --accept text/uri-list --out "$OUT/t8.data"
start_source s8 --offer "image/png=$IMAGE"
paste_to s8 t8
wait_line "$OUT/t8.log" "SELECTION image/png" 10 || true
check "other apps see the clipboard exactly as offered" has "$OUT/t8.log" "SELECTION image/png"
stop_clients

# ── 9. a sandboxed app's files (FileTransfer key only) into a host app ────────────────────
echo "itest: drag portal-only files into a host app"
start_target t9 host --actions 1 --preferred 1 --accept $URI --out "$OUT/t9.data"
start_source s9 --actions 7 --portal-file "$OUT/files/a b.txt"
drag s9 t9
